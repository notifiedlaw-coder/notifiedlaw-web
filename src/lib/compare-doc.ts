import { buildDocx, type Block } from "@/lib/docx";
import type { Comparison } from "@/lib/compare";

const dateText = (d: Date) => new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "Africa/Accra" }).format(d);

/** A case comparison as a Word document with the cases' details, the AI's comparison and where it came from. */
export function comparisonDocx(c: Comparison, model: string, now = new Date()) {
  const [a, b] = c.cases;
  const blocks: Block[] = [
    { t: "title", text: "Case comparison" },
    { t: "p", text: `${a.title} v ${b.title}` },
    { t: "note", text: `Generated by NotifiedLaw AI (${model}) on ${dateText(now)} from the case briefs on notifiedlaw.com. AI can make mistakes: check it against the full judgments before relying on it.` },
    { t: "h1", text: "The cases" },
    { t: "table", head: ["", "Case A", "Case B"], rows: [
      ["Case", a.title, b.title],
      ["Citation", a.cite || "Not given", b.cite || "Not given"],
      ["Court", a.court || "Not given", b.court || "Not given"],
      ["Jurisdiction", a.jurisdiction || "Not given", b.jurisdiction || "Not given"],
      ["Brief", `notifiedlaw.com/case-law/${a.slug}`, `notifiedlaw.com/case-law/${b.slug}`],
    ] },
    { t: "h1", text: "Summary" },
    { t: "p", text: c.summary },
    { t: "h1", text: "Side by side" },
    { t: "table", head: ["", a.title, b.title], rows: c.aspects.map((x) => [x.label, x.a, x.b]) },
    { t: "h1", text: "What they share" },
    ...c.similarities.map((text): Block => ({ t: "bullet", text })),
    { t: "h1", text: "Where they differ" },
    ...c.differences.map((text): Block => ({ t: "bullet", text })),
    { t: "h1", text: "Which to cite" },
    { t: "p", text: c.takeaway },
  ];
  return buildDocx(blocks);
}

/** The saved file's name, e.g. "Comparison - Tsatsu Tsikata v Attorney-General.docx" (cleaned further on save). */
export const comparisonFileName = (c: Comparison) => `Comparison - ${c.cases[0].title} v ${c.cases[1].title}`.slice(0, 110) + ".docx";
